"""Offline evaluation. Writes docs/evaluation.md.

    python -m sp.evaluate
"""
import datetime
import pathlib

from . import engine, seed, world


def main():
    _, m = seed.train()
    w = world.build(today=datetime.date(2026, 10, 1))
    inv = [{"id": i, "vendor_id": x["vendor"], "alias_id": x["alias"], "number": x["number"], "date": x["date"], "total": x["total"]} for i, x in enumerate(w["invoices"])]
    true = {(x["dup_of"], i) for i, x in enumerate(w["invoices"]) if x["dup_of"] is not None}
    found = {(d["original"], d["duplicate"]) for d in engine.duplicates(inv)}
    naive = {(d["original"], d["duplicate"]) for d in engine.duplicates(inv, by="alias_id")}
    rate_ok = reb_ok = reb_n = 0
    for k in w["contracts"]:
        terms = engine.extract_terms(k["text"])
        rate_ok += {t["key"]: t["value"] for t in terms if t["term_type"] == "rate_card"} == (k["rates"] or {})
        if k["rebate"]:
            reb_n += 1
            r = {t["key"]: t["value"] for t in terms if t["term_type"] == "rebate"}
            reb_ok += (r.get("threshold"), r.get("percent")) == (float(k["rebate"][0]), float(k["rebate"][1]))
    er, cl = m["entity_resolution"], m["classification"]
    pr = lambda s: f"{len(s & true)} of {len(true)} found, {len(s - true)} false"      # noqa: E731
    lines = ["# Evaluation", "",
             f"Generated by `python -m sp.evaluate`. The ledger is synthetic ({len(w['invoices']):,} invoices, {len(w['lines']):,} lines, {len(w['aliases'])} vendor records for {len(w['vendors'])} companies over three years)",
             "and the leakage in it was planted, so every engine can be scored against a known answer. Real ledgers are messier: read these as a check that the engines work, not as expected accuracy.", "",
             "## 1. Vendor entity resolution", "",
             "The pair model is fitted on one synthetic world and scored on another it never saw (different companies, different spellings). Pairwise scores:", "",
             "| | Precision | Recall | F1 |", "|---|---|---|---|",
             f"| Logistic regression on name, tax id, bank and address evidence (`{engine.VERSION}`) | {er['model']['precision']} | {er['model']['recall']} | {er['model']['f1']} |",
             f"| Baseline: identical name after normalisation | {er['baseline']['precision']} | {er['baseline']['recall']} | {er['baseline']['f1']} |", "",
             "## 2. Spend classification", "",
             f"Character n-gram TF-IDF + logistic regression over 21 categories, fitted on one world and scored on {cl['model']['n_test']:,} lines of another.", "",
             "| | Accuracy |", "|---|---|", f"| Classifier | {cl['model']['accuracy']:.1%} |", f"| Baseline: keyword rules | {cl['baseline']['accuracy']:.1%} |", "",
             "The synthetic descriptions come from a small phrase bank per category, which is why the classifier is nearly perfect. Free-text descriptions from real buyers would not be.", "",
             "## 3. Duplicate invoices", "",
             "| | Planted duplicates |", "|---|---|", f"| Resolved vendor + amount + date window + invoice number reduced to its digits | {pr(found)} |",
             f"| Baseline: same vendor record, identical number and amount | {pr(naive)} |", "",
             f"{sum(w['invoices'][b]['alias'] != w['invoices'][a]['alias'] for a, b in true)} of the planted duplicates were entered under a different spelling of the vendor: they only become findable after resolution.", "",
             "## 4. Contract term extraction", "",
             f"{rate_ok} of {len(w['contracts'])} contracts had their rate card (or its absence) read exactly; {reb_ok} of {reb_n} rebate clauses were read with the right threshold and percentage.",
             "The contracts are generated from three phrasings per clause, and the extractor is a set of regular expressions written against those phrasings. It would need a language model, or many more",
             "rules, for real contracts; what carries over is the output shape: every term with the clause and sentence it was read from.", "",
             "## 5. Leakage", "",
             "Checked in the end-to-end test against the planted truth for the imported year: overbilling within 1%, missed rebates within 5%, duplicate payments within 3 pairs (`tests/test_api.py`)."]
    out = pathlib.Path(__file__).resolve().parent.parent / "docs" / "evaluation.md"
    out.write_text("\n".join(lines) + "\n")
    print(out.read_text())


if __name__ == "__main__":
    main()
